import { readFile } from "node:fs/promises";
import path from "node:path";
import { PDFDocument, PDFPage } from "pdf-lib";
import sharp from "sharp";
import {
  Cell,
  Fonts,
  INK,
  NOTE_GREY,
  fitSize,
  fmtDate,
  loadFonts,
  placeSignature,
  safeText,
  signatureToPng,
} from "./pdf-helpers";
import { PackData, PackLogEntry, TRAINING_LABEL } from "./types";
import { rgb } from "pdf-lib";

// Certified copy of the student's logbook for the SAHPA/CAA pack (Riaan, 14
// Oct 2026): name, photo and licence numbers at the top; every flight with
// its instructor sign-off; signed off by the student and the instructor at
// the end. A4 landscape.

const W = 841.89;
const H = 595.28;
const M = 28; // margin
const ROW_H = 17;

const COLS: { key: string; label: string; w: number }[] = [
  { key: "n", label: "#", w: 24 },
  { key: "date", label: "Date", w: 52 },
  { key: "site", label: "Site", w: 110 },
  { key: "aircraft", label: "Aircraft / equipment", w: 150 },
  { key: "type", label: "Type", w: 34 },
  { key: "dur", label: "Time", w: 38 },
  { key: "launches", label: "Launches", w: 42 },
  { key: "ex", label: "Exercises", w: 92 },
  { key: "instr", label: "Instructor", w: 90 },
  { key: "signed", label: "Signed off by instructor", w: 178 },
];

function hm(min: number): string {
  return `${Math.floor(min / 60)}:${String(min % 60).padStart(2, "0")}`;
}
function typeLabel(t: string): string {
  return t === "winching" ? "Winch" : t.toUpperCase();
}
function ellipsize(fonts: Fonts, text: string, size: number, maxW: number, bold = false): string {
  const font = bold ? fonts.bold : fonts.regular;
  let t = safeText(text);
  if (font.widthOfTextAtSize(t, size) <= maxW) return t;
  while (t.length > 1 && font.widthOfTextAtSize(t + "...", size) > maxW) t = t.slice(0, -1);
  return t + "...";
}

export async function buildLogbookPdf(d: PackData, photoJpeg: Buffer | null): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const fonts = await loadFonts(doc);
  const s = d.student;
  const entries = d.logbook;

  // Pre-compute pagination: first page has the big header, later pages a slim one.
  const firstTop = 150;
  const nextTop = 58;
  const bottom = H - 36;
  const perFirst = Math.max(1, Math.floor((bottom - firstTop - ROW_H) / ROW_H));
  const perNext = Math.max(1, Math.floor((bottom - nextTop - ROW_H) / ROW_H));
  const pagesRows: PackLogEntry[][] = [];
  let i = 0;
  pagesRows.push(entries.slice(i, i + perFirst));
  i += perFirst;
  while (i < entries.length) {
    pagesRows.push(entries.slice(i, i + perNext));
    i += perNext;
  }

  const totalMin = entries.reduce((a, e) => a + e.durationMinutes, 0);
  const totalLaunches = entries.reduce((a, e) => a + e.launches, 0);
  const byType: Record<string, number> = {};
  for (const e of entries) byType[typeLabel(e.flightType)] = (byType[typeLabel(e.flightType)] ?? 0) + e.durationMinutes;

  // Where the declaration block goes: on the last table page if it fits.
  const lastRows = pagesRows[pagesRows.length - 1].length;
  const lastTop = pagesRows.length === 1 ? firstTop : nextTop;
  const usedBottom = lastTop + ROW_H + lastRows * ROW_H + 34; // + totals line
  const declNeeds = 150;
  const declOnSeparatePage = usedBottom + declNeeds > bottom + 10;
  const totalPages = pagesRows.length + (declOnSeparatePage ? 1 : 0);

  const logo = await readFile(path.join(process.cwd(), "public", "apex-logo.png"))
    .then((b) => sharp(b).resize({ width: 300, withoutEnlargement: true }).png().toBuffer())
    .then((b) => doc.embedPng(b))
    .catch(() => null);
  const photo = photoJpeg ? await doc.embedJpg(photoJpeg) : null;

  const studentPng = d.studentSignature ? await signatureToPng(d.studentSignature) : null;
  const instructorPng = d.instructorSignature ? await signatureToPng(d.instructorSignature) : null;

  const drawFooter = (page: PDFPage, n: number) => {
    const t = `${safeText(s.fullName)} - logbook copy - generated by Apex Flight Hub on ${fmtDate(d.signedOffAt)}`;
    page.drawText(t, { x: M, y: 18, size: 7, font: fonts.regular, color: NOTE_GREY });
    const pg = `Page ${n} of ${totalPages}`;
    page.drawText(pg, { x: W - M - fonts.regular.widthOfTextAtSize(pg, 7), y: 18, size: 7, font: fonts.regular, color: NOTE_GREY });
  };

  const drawTableHeader = (page: PDFPage, top: number) => {
    let x = M;
    page.drawRectangle({ x: M, y: H - (top + ROW_H), width: COLS.reduce((a, c) => a + c.w, 0), height: ROW_H, color: rgb(0.9, 0.92, 0.96) });
    for (const col of COLS) {
      page.drawText(ellipsize(fonts, col.label, 7, col.w - 4, true), { x: x + 2, y: H - (top + 11.5), size: 7, font: fonts.bold, color: rgb(0, 0, 0) });
      x += col.w;
    }
  };

  const drawRow = (page: PDFPage, top: number, n: number, e: PackLogEntry) => {
    const rowTotalW = COLS.reduce((a, c) => a + c.w, 0);
    page.drawLine({ start: { x: M, y: H - (top + ROW_H) }, end: { x: M + rowTotalW, y: H - (top + ROW_H) }, thickness: 0.3, color: rgb(0.75, 0.75, 0.75) });
    const signed = e.verified
      ? `OK ${e.verifiedByName ?? "Instructor"}${e.verifiedAt ? " " + fmtDate(e.verifiedAt) : ""}`
      : "NOT COUNTERSIGNED";
    const cells: Record<string, string> = {
      n: String(n),
      date: fmtDate(e.date),
      site: e.site,
      aircraft: e.aircraftType,
      type: typeLabel(e.flightType),
      dur: hm(e.durationMinutes),
      launches: String(e.launches),
      ex: e.exerciseCodes ?? "",
      instr: e.instructorName ?? "",
      signed,
    };
    let x = M;
    for (const col of COLS) {
      const txt = ellipsize(fonts, cells[col.key], 7, col.w - 4);
      const isWarn = col.key === "signed" && !e.verified;
      page.drawText(txt, {
        x: x + 2,
        y: H - (top + 11.5),
        size: 7,
        font: fonts.regular,
        color: isWarn ? rgb(0.75, 0.1, 0.1) : INK,
      });
      x += col.w;
    }
  };

  const drawDeclaration = async (page: PDFPage, top: number) => {
    page.drawText("DECLARATION", { x: M, y: H - top, size: 9, font: fonts.bold, color: rgb(0, 0, 0) });
    const lines = [
      "Student: I declare that the flights recorded in this logbook are a true and complete record of my flying.",
      "Instructor: I confirm that the flights above were countersigned by an instructor of the DTO and that the student has completed the training required.",
    ];
    lines.forEach((ln, k) =>
      page.drawText(safeText(ln), { x: M, y: H - (top + 12 + k * 10), size: 7.5, font: fonts.regular, color: rgb(0.15, 0.15, 0.15) })
    );
    const boxTop = top + 34;
    const boxH = 62;
    const cols = [
      { title: "SIGNATURE OF STUDENT", x: M, w: 200 },
      { title: "NAME", x: M + 200, w: 150 },
      { title: "DATE", x: M + 350, w: 90 },
      { title: "SIGNATURE OF INSTRUCTOR", x: M + 450, w: 200 },
    ];
    // Two rows: student (left three boxes) and instructor (right box + name/date below)
    const drawBox = (x: number, y: number, w: number, h: number, label: string) => {
      page.drawRectangle({ x, y: H - (y + h), width: w, height: h, borderColor: rgb(0.3, 0.3, 0.3), borderWidth: 0.6 });
      page.drawText(label, { x: x + 3, y: H - (y + h) + 3, size: 6, font: fonts.bold, color: NOTE_GREY });
    };
    // Student row
    drawBox(cols[0].x, boxTop, cols[0].w, boxH, "SIGNATURE OF STUDENT");
    drawBox(cols[1].x, boxTop, cols[1].w, boxH, "NAME IN BLOCK LETTERS");
    drawBox(cols[2].x, boxTop, cols[2].w, boxH, "DATE");
    // Instructor row (to the right)
    const ix = M + 450;
    drawBox(ix, boxTop, 130, boxH, "SIGNATURE OF INSTRUCTOR");
    drawBox(ix + 130, boxTop, 120, boxH, "NAME / LICENCE NO. / DATE");
    page.drawText(safeText(s.fullName).toUpperCase(), { x: cols[1].x + 4, y: H - (boxTop + 30), size: 8.5, font: fonts.regular, color: INK });
    page.drawText(safeText(d.instructor.fullName), { x: ix + 134, y: H - (boxTop + 22), size: 8, font: fonts.regular, color: INK });
    page.drawText(safeText(d.instructor.licenceNumber), { x: ix + 134, y: H - (boxTop + 34), size: 8, font: fonts.regular, color: INK });
    if (studentPng) {
      await placeSignature(doc, page, fonts, studentPng, { x0: cols[0].x + 2, x1: cols[0].x + cols[0].w - 2, y0: boxTop + 2, y1: boxTop + boxH - 9 }, `Digitally signed by ${s.fullName} - ${fmtDate(d.signedOffAt)}`);
      page.drawText(fmtDate(d.signedOffAt), { x: cols[2].x + 4, y: H - (boxTop + 30), size: 8.5, font: fonts.regular, color: INK });
    }
    if (instructorPng) {
      await placeSignature(doc, page, fonts, instructorPng, { x0: ix + 2, x1: ix + 128, y0: boxTop + 2, y1: boxTop + boxH - 9 }, `Digitally signed by ${d.instructor.fullName} - ${fmtDate(d.signedOffAt)}`);
      page.drawText(fmtDate(d.signedOffAt), { x: ix + 134, y: H - (boxTop + 46), size: 8, font: fonts.regular, color: INK });
    }
    if (!studentPng || !instructorPng) {
      page.drawText(
        safeText("Where a signature box is empty, sign by hand on the printed copy."),
        { x: M, y: H - (boxTop + boxH + 12), size: 6.5, font: fonts.regular, color: NOTE_GREY }
      );
    }
  };

  let n = 0;
  for (let pi = 0; pi < pagesRows.length; pi++) {
    const page = doc.addPage([W, H]);
    let top: number;
    if (pi === 0) {
      // Big header
      if (logo) {
        const lw = 70;
        page.drawImage(logo, { x: M, y: H - 20 - (logo.height * lw) / logo.width, width: lw, height: (logo.height * lw) / logo.width });
      }
      page.drawText("STUDENT FLIGHT LOGBOOK - CERTIFIED COPY", { x: M + 90, y: H - 34, size: 15, font: fonts.bold, color: rgb(0, 0, 0) });
      page.drawText(`For SAHPA / CAA licence submission - ${TRAINING_LABEL[d.trainingType]}`, { x: M + 90, y: H - 48, size: 9, font: fonts.regular, color: NOTE_GREY });
      const details: [string, string][] = [
        ["Name", s.fullName],
        ["Apex No.", s.apexNumber ?? ""],
        ["ID / passport", s.idPassport],
        ["SACAA No.", s.sacaaNumber ?? ""],
        ["SAHPA No.", s.sahpaNumber ? `${s.sahpaNumber}${s.sahpaExpiry ? "  (expires " + fmtDate(s.sahpaExpiry) + ")" : ""}` : ""],
        ["Licence no.", s.licenceNumber ?? "None yet - initial application"],
        ["Call sign", s.callSign ?? ""],
        ["DTO", `${d.dtoName} (${d.dtoNumber})`],
      ];
      let dy = 68;
      for (let k = 0; k < details.length; k++) {
        const col = k < 4 ? 0 : 1;
        const row = k % 4;
        const x = M + col * 330;
        page.drawText(details[k][0] + ":", { x, y: H - (dy + row * 14), size: 8, font: fonts.bold, color: rgb(0.2, 0.2, 0.2) });
        page.drawText(ellipsize(fonts, details[k][1], 9, 230), { x: x + 72, y: H - (dy + row * 14), size: 9, font: fonts.regular, color: INK });
      }
      if (photo) {
        const ph = 92;
        const pw = (photo.width * ph) / photo.height;
        page.drawImage(photo, { x: W - M - pw, y: H - 20 - ph, width: pw, height: ph });
        page.drawRectangle({ x: W - M - pw, y: H - 20 - ph, width: pw, height: ph, borderColor: rgb(0.4, 0.4, 0.4), borderWidth: 0.5 });
      }
      top = firstTop;
    } else {
      page.drawText(`${safeText(s.fullName)} - flight logbook (continued)`, { x: M, y: H - 34, size: 10, font: fonts.bold, color: rgb(0, 0, 0) });
      top = nextTop;
    }
    drawTableHeader(page, top);
    let rowTop = top + ROW_H;
    for (const e of pagesRows[pi]) {
      n++;
      drawRow(page, rowTop, n, e);
      rowTop += ROW_H;
    }
    const isLast = pi === pagesRows.length - 1;
    if (isLast) {
      const totals = `Total: ${entries.length} flights   ${hm(totalMin)} h   ${totalLaunches} launches   (${Object.entries(byType)
        .map(([k, v]) => `${k} ${hm(v)}`)
        .join(", ")})`;
      page.drawText(safeText(totals), { x: M, y: H - (rowTop + 14), size: 8.5, font: fonts.bold, color: rgb(0, 0, 0) });
      if (!declOnSeparatePage) await drawDeclaration(page, rowTop + 34);
    }
    drawFooter(page, pi + 1);
  }
  if (entries.length === 0) {
    // keep a valid doc when there are no flights
    const page = doc.getPages()[0];
    page.drawText("No flights recorded.", { x: M, y: H - 170, size: 9, font: fonts.regular, color: INK });
  }
  if (declOnSeparatePage) {
    const page = doc.addPage([W, H]);
    page.drawText(`${safeText(s.fullName)} - flight logbook (declaration)`, { x: M, y: H - 34, size: 10, font: fonts.bold, color: rgb(0, 0, 0) });
    await drawDeclaration(page, 70);
    drawFooter(page, totalPages);
  }
  return doc.save();
}
